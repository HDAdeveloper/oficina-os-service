-- OS Service: banco próprio, nenhum outro serviço acessa estas tabelas.

CREATE TABLE cliente (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(150) NOT NULL,
    documento      VARCHAR(14)  NOT NULL,
    tipo_documento VARCHAR(10)  NOT NULL,
    email          VARCHAR(150),
    telefone       VARCHAR(30),
    endereco       VARCHAR(255),
    ativo          BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_cliente_documento UNIQUE (documento)
);

CREATE TABLE veiculo (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa      VARCHAR(7)   NOT NULL,
    marca      VARCHAR(80)  NOT NULL,
    modelo     VARCHAR(80)  NOT NULL,
    ano        INTEGER      NOT NULL,
    cliente_id BIGINT       NOT NULL REFERENCES cliente (id),
    ativo      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_veiculo_placa UNIQUE (placa)
);
CREATE INDEX idx_veiculo_cliente ON veiculo (cliente_id);

CREATE TABLE servico (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                   VARCHAR(150)   NOT NULL,
    descricao              VARCHAR(500),
    preco                  NUMERIC(12, 2) NOT NULL,
    tempo_estimado_minutos INTEGER        NOT NULL,
    ativo                  BOOLEAN        NOT NULL DEFAULT TRUE
);

CREATE TABLE peca (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         VARCHAR(40)    NOT NULL,
    nome           VARCHAR(150)   NOT NULL,
    descricao      VARCHAR(500),
    preco_unitario NUMERIC(12, 2) NOT NULL,
    ativo          BOOLEAN        NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_peca_codigo UNIQUE (codigo)
);

CREATE TABLE ordem_servico (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao               BIGINT       NOT NULL DEFAULT 0,
    numero               VARCHAR(40)  NOT NULL,
    cliente_id           BIGINT       NOT NULL REFERENCES cliente (id),
    veiculo_id           BIGINT       NOT NULL REFERENCES veiculo (id),
    status               VARCHAR(30)  NOT NULL,
    descricao_problema   VARCHAR(1000) NOT NULL,
    observacoes          VARCHAR(1000),
    orcamento_id         VARCHAR(64),
    motivo_cancelamento  VARCHAR(500),
    data_abertura        TIMESTAMP WITH TIME ZONE NOT NULL,
    data_inicio          TIMESTAMP WITH TIME ZONE,
    data_finalizacao     TIMESTAMP WITH TIME ZONE,
    data_entrega         TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_os_numero UNIQUE (numero)
);
CREATE INDEX idx_os_status ON ordem_servico (status);
CREATE INDEX idx_os_cliente ON ordem_servico (cliente_id);

CREATE TABLE os_item_servico (
    os_id          BIGINT         NOT NULL REFERENCES ordem_servico (id) ON DELETE CASCADE,
    ordem          INTEGER        NOT NULL,
    servico_id     BIGINT         NOT NULL,
    nome           VARCHAR(150)   NOT NULL,
    quantidade     INTEGER        NOT NULL,
    preco_unitario NUMERIC(12, 2) NOT NULL,
    PRIMARY KEY (os_id, ordem)
);

CREATE TABLE os_item_peca (
    os_id          BIGINT         NOT NULL REFERENCES ordem_servico (id) ON DELETE CASCADE,
    ordem          INTEGER        NOT NULL,
    peca_id        BIGINT         NOT NULL,
    codigo         VARCHAR(40)    NOT NULL,
    nome           VARCHAR(150)   NOT NULL,
    quantidade     INTEGER        NOT NULL,
    preco_unitario NUMERIC(12, 2) NOT NULL,
    PRIMARY KEY (os_id, ordem)
);

CREATE TABLE os_historico (
    os_id  BIGINT       NOT NULL REFERENCES ordem_servico (id) ON DELETE CASCADE,
    ordem  INTEGER      NOT NULL,
    de     VARCHAR(30),
    para   VARCHAR(30)  NOT NULL,
    em     TIMESTAMP WITH TIME ZONE NOT NULL,
    motivo VARCHAR(500),
    PRIMARY KEY (os_id, ordem)
);
