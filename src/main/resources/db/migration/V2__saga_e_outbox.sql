-- Estado do orquestrador da Saga, idempotência das mensagens recebidas e outbox dos comandos enviados.
-- Tudo é gravado na mesma transação do estado da OS (ver docs/eventos.md, regra 4).

CREATE TABLE saga_instance (
    id               VARCHAR(64)  PRIMARY KEY,
    versao           BIGINT       NOT NULL DEFAULT 0,
    os_id            BIGINT       NOT NULL REFERENCES ordem_servico (id),
    correlation_id   VARCHAR(100),
    estado           VARCHAR(30)  NOT NULL,
    orcamento_id     VARCHAR(64),
    valor_total      NUMERIC(12, 2),
    metodo_pagamento VARCHAR(40),
    pagamento_id     VARCHAR(64),
    reserva_id       VARCHAR(64),
    motivo           VARCHAR(1000),
    tentativas       INTEGER      NOT NULL DEFAULT 0,
    prazo            TIMESTAMP WITH TIME ZONE,
    criada_em        TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizada_em    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_saga_os ON saga_instance (os_id, criada_em DESC);
CREATE INDEX idx_saga_prazo ON saga_instance (prazo) WHERE prazo IS NOT NULL;

-- Diário da Saga: comandos enviados, eventos recebidos e mudanças de estado
CREATE TABLE saga_passo (
    saga_id VARCHAR(64)   NOT NULL REFERENCES saga_instance (id) ON DELETE CASCADE,
    ordem   INTEGER       NOT NULL,
    em      TIMESTAMP WITH TIME ZONE NOT NULL,
    tipo    VARCHAR(40)   NOT NULL,
    detalhe VARCHAR(1000),
    PRIMARY KEY (saga_id, ordem)
);

-- Mensagens já tratadas (a entrega do SQS é at-least-once)
CREATE TABLE mensagem_processada (
    message_id    VARCHAR(64) PRIMARY KEY,
    processada_em TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Outbox dos comandos: gravados com o estado e enviados ao SNS por um relay
CREATE TABLE outbox_comando (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id     VARCHAR(36)   NOT NULL,
    tipo           VARCHAR(60)   NOT NULL,
    destino        VARCHAR(20)   NOT NULL,
    os_id          BIGINT,
    saga_id        VARCHAR(64),
    correlation_id VARCHAR(100),
    payload        VARCHAR(8000) NOT NULL,
    criado_em      TIMESTAMP WITH TIME ZONE NOT NULL,
    publicado_em   TIMESTAMP WITH TIME ZONE,
    tentativas     INTEGER       NOT NULL DEFAULT 0,
    ultimo_erro    VARCHAR(500),
    CONSTRAINT uk_outbox_comando_message UNIQUE (message_id)
);
CREATE INDEX idx_outbox_comando_pendentes ON outbox_comando (id) WHERE publicado_em IS NULL;
